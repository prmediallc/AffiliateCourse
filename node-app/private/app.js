function applyAdminCustomization() {
  const settings = JSON.parse(localStorage.getItem("pr-media-admin-settings") || "{}");
  if (settings.title) document.title = settings.title;
  if (settings.instructor) {
    document.querySelectorAll(".instructor h2").forEach((node) => {
      node.textContent = settings.instructor;
    });
  }
  if (settings.email) {
    document.querySelectorAll("[href^='mailto:']").forEach((link) => {
      link.href = `mailto:${settings.email}`;
    });
  }
  adminTitle.value = settings.title || "";
  adminInstructor.value = settings.instructor || "";
  adminEmail.value = settings.email || "";
}

async function loadServerState() {
  try {
    const [settingsResponse, progressResponse] = await Promise.all([
      fetch("/api/settings"),
      fetch("/api/progress"),
    ]);

    if (settingsResponse.ok) {
      const settings = await settingsResponse.json();
      localStorage.setItem(
        "pr-media-admin-settings",
        JSON.stringify({
          title: settings.portalTitle,
          instructor: settings.instructorName,
          email: settings.supportEmail,
        })
      );
    }

    if (progressResponse.ok) {
      const progress = await progressResponse.json();
      if (progress.activeCourseKey === activeCourseKey) {
        completedLessons = new Set(progress.completedLessons || []);
        viewerTasks = new Set(progress.viewerTasks || []);
      }
    }
  } catch {
    // The course still works with browser storage during offline development.
  }
}

function saveProgress() {
  localStorage.setItem(`${storageKeyBase}-${activeCourseKey}`, JSON.stringify([...completedLessons]));
  syncProgressToServer();
}

function saveViewerTasks() {
  localStorage.setItem(`${viewerStorageKeyBase}-${activeCourseKey}`, JSON.stringify([...viewerTasks]));
  syncProgressToServer();
}

async function syncProgressToServer() {
  try {
    await fetch("/api/progress", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        activeCourseKey,
        completedLessons: [...completedLessons],
        viewerTasks: [...viewerTasks],
      }),
    });
  } catch {
    // Local browser progress remains available if the API is unavailable.
  }
}

function updateProgress() {
  const totalLessons = modules.reduce((total, module) => total + module.lessons.length, 0);
  const percent = Math.round((completedLessons.size / totalLessons) * 100);
  progressText.textContent = `${percent}%`;
  progressBar.style.width = `${percent}%`;
}

function getModuleDuration(moduleIndex) {
  const lessonCount = modules[moduleIndex].lessons.length;
  if (lessonCount >= 6) return "Est. 3-4 hours";
  if (lessonCount === 5) return "Est. 2-3 hours";
  return "Est. 2 hours";
}

