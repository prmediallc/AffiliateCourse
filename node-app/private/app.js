function renderLessonViewer(moduleIndex = activeModuleIndex, lessonIndex = activeLessonIndex) {
  activeModuleIndex = moduleIndex;
  activeLessonIndex = lessonIndex;

  const module = modules[moduleIndex];
  const [title, description] = module.lessons[lessonIndex];
  const lessonId = `${moduleIndex}-${lessonIndex}`;
  const detail = getLessonDetail(lessonId, title, description, lessonIndex + 1);
  const moduleNumber = String(moduleIndex + 1).padStart(2, "0");
  const taskIds = detail.checklist.map((_, index) => `${lessonId}-task-${index}`);
  const doneCount = taskIds.filter((id) => viewerTasks.has(id)).length;
  const moduleTaskTotal = module.lessons.reduce((total, lesson, index) => {
    const id = `${moduleIndex}-${index}`;
    return total + getLessonDetail(id, lesson[0], lesson[1], index + 1).checklist.length;
  }, 0);
  const moduleTaskDone = module.lessons.reduce((total, lesson, index) => {
    const id = `${moduleIndex}-${index}`;
    const lessonDetail = getLessonDetail(id, lesson[0], lesson[1], index + 1);
    return total + lessonDetail.checklist.filter((_, taskIndex) => viewerTasks.has(`${id}-task-${taskIndex}`)).length;
  }, 0);
  const percent = Math.round((doneCount / taskIds.length) * 100);

  lessonViewer.innerHTML = `
    <section class="viewer-hero">
      <span class="eyebrow">Module</span>
      <h2>${module.title}</h2>
      <p>${module.lessons.length} lessons · ${getModuleDuration(moduleIndex)} · ${courses[activeCourseKey].stats[3]}</p>
      <span class="viewer-number">${moduleNumber}</span>
    </section>

    <section class="viewer-stats" aria-label="Module stats">
      <article class="viewer-stat"><strong>${module.lessons.length}</strong><span>Lessons</span></article>
      <article class="viewer-stat"><strong>${module.lessons.length >= 6 ? "4h" : module.lessons.length === 5 ? "3h" : "2h"}</strong><span>Duration</span></article>
      <article class="viewer-stat"><strong>${moduleIndex === 0 ? 6 : moduleIndex === 1 ? 4 : moduleIndex === 2 ? 1 : 0}</strong><span>Accounts</span></article>
      <article class="viewer-stat"><strong>0</strong><span>Cost (AED)</span></article>
    </section>

    <nav class="lesson-tabs" aria-label="Lesson tabs">
      ${module.lessons
        .map((_, index) => `
          <button class="lesson-tab ${index === lessonIndex ? "active" : ""}" type="button" data-viewer-lesson="${index}">
            L${index + 1}
          </button>
        `)
        .join("")}
    </nav>

    <div class="viewer-progress-line">
      <span>Lesson ${lessonIndex + 1} of ${module.lessons.length}</span>
      <span></span>
      <span>${moduleTaskDone} / ${moduleTaskTotal} tasks done</span>
      <div class="progress-track"><div class="progress-bar" style="width: ${percent}%"></div></div>
    </div>

    <article class="viewer-lesson-card">
      <header class="viewer-lesson-head">
        <div class="viewer-icon">📧</div>
        <div>
          <h3>Lesson ${lessonIndex + 1} — ${title}</h3>
          <p>${detail.meta}</p>
        </div>
      </header>
      <div class="viewer-lesson-body">
        <section class="objective-box">
          <strong>Objective</strong>
          <p>${detail.objective}</p>
        </section>
        <section class="viewer-steps">
          ${detail.steps
            .map(([stepTitle, stepBody], index) => `
              <div class="viewer-step">
                <span>${index + 1}</span>
                <div>
                  <strong>${stepTitle}</strong>
                  <p>${stepBody}</p>
                </div>
              </div>
            `)
            .join("")}
        </section>
        <div class="viewer-tip">${detail.tip}</div>
        <div class="viewer-checklist">
          ${detail.checklist
            .map((item, index) => {
              const taskId = `${lessonId}-task-${index}`;
              const checked = viewerTasks.has(taskId) ? "checked" : "";
              return `
                <label class="viewer-check">
                  <input type="checkbox" data-viewer-task="${taskId}" ${checked}>
                  <span>${item}</span>
                </label>
              `;
            })
            .join("")}
        </div>
      </div>
    </article>

    <button class="next-lesson" type="button" id="nextLesson">Next lesson ➜</button>
  `;
}

